def _read_csv(name):
    path = os.path.join(HERE, name)
    if not os.path.exists(path):
        return []
    rows = []
    for line in open(path, encoding="utf-8-sig"):
        p = [x.strip() for x in line.split(",")]
        if p and p[0] and not p[0].startswith("#"):
            rows.append(p)
    return rows


